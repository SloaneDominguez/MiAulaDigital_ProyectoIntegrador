/*
|--------------------------------------------------------------------------
| Limpiar texto
|--------------------------------------------------------------------------
*/

function limpiarTexto(string $texto): string
{
    return trim($texto);
}

/*
|--------------------------------------------------------------------------
| Escapar HTML
|--------------------------------------------------------------------------
*/

function e(string $texto): string
{
    return htmlspecialchars($texto, ENT_QUOTES, 'UTF-8');
}

/*
|--------------------------------------------------------------------------
| Redireccionar
|--------------------------------------------------------------------------
*/

function redireccionar(string $url): void
{
    header("Location: {$url}");
    exit;
}

/*
|--------------------------------------------------------------------------
| Validar correo
|--------------------------------------------------------------------------
*/

function validarCorreo(string $correo): bool
{
    return filter_var($correo, FILTER_VALIDATE_EMAIL);
}

/*
|--------------------------------------------------------------------------
| Validar usuario
|--------------------------------------------------------------------------
*/

function validarUsuario(string $usuario): bool
{
    return preg_match('/^[A-Za-z0-9._-]{4,30}$/', $usuario);
}

/*
|--------------------------------------------------------------------------
| Validar teléfono
|--------------------------------------------------------------------------
*/

function validarTelefono(string $telefono): bool
{
    return preg_match('/^[0-9]{10}$/', $telefono);
}

/*
|--------------------------------------------------------------------------
| Validar CURP
|--------------------------------------------------------------------------
*/

function validarCURP(string $curp): bool
{
    return preg_match('/^[A-Z]{4}[0-9]{6}[HM][A-Z]{5}[A-Z0-9]{2}$/', strtoupper($curp));
}

/*
|--------------------------------------------------------------------------
| Validar Token
|--------------------------------------------------------------------------
*/

function validarTokenAcceso(string $token): bool
{
    return preg_match('/^[A-Za-z0-9-]{6,50}$/', $token);
}

/*
|--------------------------------------------------------------------------
| Validar contraseña
|--------------------------------------------------------------------------
*/

function validarPassword(string $password): bool
{
    return preg_match(
        '/^(?=.*[a-z])(?=.*[A-Z])(?=.*[0-9]).{8,50}$/',
        $password
    );
}

/*
|--------------------------------------------------------------------------
| IP
|--------------------------------------------------------------------------
*/

function obtenerIP(): string
{
    return $_SERVER['REMOTE_ADDR'] ?? '0.0.0.0';
}

/*
|--------------------------------------------------------------------------
| Navegador
|--------------------------------------------------------------------------
*/

function obtenerNavegador(): string
{
    return $_SERVER['HTTP_USER_AGENT'] ?? 'Desconocido';
}